const DIA = (data) => Math.floor(new Date(`${data}T12:00`).getTime() / 864e5);
const ordem = (() => {
	const R = rng('radix-frases');
	return GERAIS.map((f, i) => ({i, s: R()})).sort((a, b) => a.s - b.s).map((x) => x.i);
})();
// seq: dias seguidos; parado: dias desde o último treino
export function fraseDoDia(data, {seq = 0, parado = 0} = {}) {
	const n = DIA(data);
	if (parado >= 3) return VOLTA[n % VOLTA.length];
	if (seq >= 14 && n % 3 === 0) return SEQUENCIA[Math.floor(n / 3) % SEQUENCIA.length];
	return GERAIS[ordem[n % ordem.length]];
}
export const totalFrases = () => GERAIS.length + SEQUENCIA.length + VOLTA.length;
